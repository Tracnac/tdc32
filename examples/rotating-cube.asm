; Four-frame 1bpp wireframe cube demo.
; Screen MMIO: $00010000-$000195FF; 64x32 pixels centered at x=320,y=240.
; Load this file, then Run at 5 ms/step. Four angles cover the cube's 90-degree symmetry.
.adr $00001000
.code start
:main
ld r1, frame0
ld r2, (cube_base)
ld r3, 32
bsr copy_rows
ld r1, frame1
ld r2, (cube_base)
ld r3, 32
bsr copy_rows
ld r1, frame2
ld r2, (cube_base)
ld r3, 32
bsr copy_rows
ld r1, frame3
ld r2, (cube_base)
ld r3, 32
bsr copy_rows
ba main

:copy_rows
:copy_loop
ld r4, (r1)
st (r2), r4
add r1, 4
ld r4, (r1)
st 4(r2), r4
add r1, 4
add r2, 80
sub r3, 1
bne copy_loop
rts

